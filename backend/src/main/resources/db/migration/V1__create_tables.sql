-- 最初のテーブル定義。H2（ローカル開発、PostgreSQL モード）と PostgreSQL（Supabase）の両方で動く書き方にする。
-- テーブルを変えるときは、このファイルを書き換えず、V2__… のように新しいファイルを追加する
-- （Flyway は適用済みのファイルが変わると、起動時にエラーで止める）。

-- ログインできる利用者
CREATE TABLE users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(20)  NOT NULL,
    email         VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    CONSTRAINT uq_users_email UNIQUE (email)
);

-- ホールスタッフ。退職は active = false で表し、行は消さない
CREATE TABLE staffs (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(20)  NOT NULL,
    position  VARCHAR(20)  NOT NULL,
    join_date DATE         NOT NULL,
    active    BOOLEAN      NOT NULL DEFAULT TRUE,
    note      VARCHAR(200) DEFAULT ''
);

-- 仕事。同じポジションに同じ名前の仕事は1つだけ
CREATE TABLE tasks (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name     VARCHAR(30) NOT NULL,
    position VARCHAR(20) NOT NULL,
    CONSTRAINT uq_tasks_name_position UNIQUE (name, position)
);

-- スタッフごと・仕事ごとの習熟度。習熟度0（未経験）は行を作らないので、値は1〜3だけ
CREATE TABLE skills (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_id   BIGINT  NOT NULL,
    task_id    BIGINT  NOT NULL,
    level      INTEGER NOT NULL,
    updated_on DATE    NOT NULL,
    CONSTRAINT uq_skills_staff_task UNIQUE (staff_id, task_id),
    CONSTRAINT fk_skills_staff FOREIGN KEY (staff_id) REFERENCES staffs (id),
    CONSTRAINT fk_skills_task FOREIGN KEY (task_id) REFERENCES tasks (id),
    CONSTRAINT ck_skills_level CHECK (level BETWEEN 1 AND 3)
);

-- 仕事ごとに「できる人」「教えられる人」を探すときに使う。
-- スタッフごとの検索は uq_skills_staff_task（staff_id が先頭）の索引で足りる
CREATE INDEX ix_skills_task_id ON skills (task_id);
